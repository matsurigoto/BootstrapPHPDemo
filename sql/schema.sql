-- ---------- USERS ----------
CREATE TABLE USERS (
    ID            NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME      VARCHAR2(128) NOT NULL UNIQUE,
    DISPLAY_NAME  VARCHAR2(256),
    EMAIL         VARCHAR2(256),
    ROLE          VARCHAR2(16)  DEFAULT 'USER' NOT NULL,
    LAST_LOGIN_AT TIMESTAMP,
    CREATED_AT    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CHK_USERS_ROLE CHECK (ROLE IN ('ADMIN','USER'))
);

-- ---------- FORMS ----------
CREATE TABLE FORMS (
    ID              NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE           VARCHAR2(512) NOT NULL,
    DESCRIPTION     CLOB,
    STATUS          VARCHAR2(16)  DEFAULT 'DRAFT' NOT NULL,
    AUDIENCE_MODE   VARCHAR2(16)  DEFAULT 'PUBLIC' NOT NULL,
    REQUIRE_LOGIN   CHAR(1)       DEFAULT 'N' NOT NULL,
    ALLOW_MULTI     CHAR(1)       DEFAULT 'N' NOT NULL,
    START_AT        TIMESTAMP,
    END_AT          TIMESTAMP,
    LOCALE_DEFAULT  VARCHAR2(16)  DEFAULT 'zh-TW' NOT NULL,
    CREATED_BY      NUMBER(19)    NOT NULL,
    CREATED_AT      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    PUBLISHED_AT    TIMESTAMP,
    CONSTRAINT CHK_FORMS_STATUS   CHECK (STATUS IN ('DRAFT','PUBLISHED','CLOSED')),
    CONSTRAINT CHK_FORMS_AUD      CHECK (AUDIENCE_MODE IN ('PUBLIC','USER','GROUP')),
    CONSTRAINT CHK_FORMS_LOGIN    CHECK (REQUIRE_LOGIN IN ('Y','N')),
    CONSTRAINT CHK_FORMS_MULTI    CHECK (ALLOW_MULTI IN ('Y','N')),
    CONSTRAINT FK_FORMS_USER      FOREIGN KEY (CREATED_BY) REFERENCES USERS(ID)
);
CREATE INDEX IX_FORMS_STATUS_TIME ON FORMS(STATUS, START_AT, END_AT);
CREATE INDEX IX_FORMS_CREATED_BY  ON FORMS(CREATED_BY);

-- ---------- FORM_AUDIENCES ----------
CREATE TABLE FORM_AUDIENCES (
    ID              NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FORM_ID         NUMBER(19)    NOT NULL,
    PRINCIPAL_TYPE  VARCHAR2(16)  NOT NULL,
    PRINCIPAL_VALUE VARCHAR2(512) NOT NULL,
    CONSTRAINT FK_AUD_FORM        FOREIGN KEY (FORM_ID) REFERENCES FORMS(ID) ON DELETE CASCADE,
    CONSTRAINT CHK_AUD_TYPE       CHECK (PRINCIPAL_TYPE IN ('USER','AD_GROUP'))
);
CREATE INDEX IX_AUD_FORM ON FORM_AUDIENCES(FORM_ID);

-- ---------- FORM_PAGES ----------
CREATE TABLE FORM_PAGES (
    ID        NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FORM_ID   NUMBER(19)    NOT NULL,
    SORT_NO   NUMBER(5)     DEFAULT 0 NOT NULL,
    TITLE     VARCHAR2(512),
    CONSTRAINT FK_PAGE_FORM   FOREIGN KEY (FORM_ID) REFERENCES FORMS(ID) ON DELETE CASCADE
);
CREATE INDEX IX_PAGE_FORM ON FORM_PAGES(FORM_ID, SORT_NO);

-- ---------- QUESTIONS ----------
CREATE TABLE QUESTIONS (
    ID          NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FORM_ID     NUMBER(19)    NOT NULL,
    PAGE_ID     NUMBER(19),
    SORT_NO     NUMBER(5)     DEFAULT 0 NOT NULL,
    TYPE        VARCHAR2(16)  NOT NULL,
    LABEL       VARCHAR2(1024) NOT NULL,
    HELP_TEXT   VARCHAR2(2000),
    REQUIRED    CHAR(1)       DEFAULT 'N' NOT NULL,
    CONFIG_JSON CLOB,
    CONSTRAINT FK_Q_FORM  FOREIGN KEY (FORM_ID) REFERENCES FORMS(ID) ON DELETE CASCADE,
    CONSTRAINT FK_Q_PAGE  FOREIGN KEY (PAGE_ID) REFERENCES FORM_PAGES(ID) ON DELETE SET NULL,
    CONSTRAINT CHK_Q_REQ  CHECK (REQUIRED IN ('Y','N')),
    CONSTRAINT CHK_Q_TYPE CHECK (TYPE IN ('TEXT','TEXTAREA','SELECT','CHECKBOX','RADIO','DATE','NUMBER','FILE','RATING'))
);
CREATE INDEX IX_Q_FORM ON QUESTIONS(FORM_ID, SORT_NO);

-- ---------- QUESTION_OPTIONS ----------
CREATE TABLE QUESTION_OPTIONS (
    ID            NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    QUESTION_ID   NUMBER(19)    NOT NULL,
    SORT_NO       NUMBER(5)     DEFAULT 0 NOT NULL,
    LABEL         VARCHAR2(1024) NOT NULL,
    OPT_VALUE     VARCHAR2(512),
    CONSTRAINT FK_OPT_Q FOREIGN KEY (QUESTION_ID) REFERENCES QUESTIONS(ID) ON DELETE CASCADE
);
CREATE INDEX IX_OPT_Q ON QUESTION_OPTIONS(QUESTION_ID, SORT_NO);

-- ---------- QUESTION_RULES (條件顯示) ----------
CREATE TABLE QUESTION_RULES (
    ID                  NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    QUESTION_ID         NUMBER(19)   NOT NULL, -- target
    SOURCE_QUESTION_ID  NUMBER(19)   NOT NULL,
    OPERATOR            VARCHAR2(8)  NOT NULL,
    COMPARE_VALUE       VARCHAR2(1024),
    ACTION              VARCHAR2(8)  DEFAULT 'SHOW' NOT NULL,
    CONSTRAINT FK_RULE_Q   FOREIGN KEY (QUESTION_ID)        REFERENCES QUESTIONS(ID) ON DELETE CASCADE,
    CONSTRAINT FK_RULE_SRC FOREIGN KEY (SOURCE_QUESTION_ID) REFERENCES QUESTIONS(ID) ON DELETE CASCADE,
    CONSTRAINT CHK_RULE_OP CHECK (OPERATOR IN ('EQ','NEQ','IN','GT','LT','CONTAINS')),
    CONSTRAINT CHK_RULE_ACT CHECK (ACTION IN ('SHOW','HIDE'))
);
CREATE INDEX IX_RULE_Q ON QUESTION_RULES(QUESTION_ID);

-- ---------- RESPONSES ----------
CREATE TABLE RESPONSES (
    ID            NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FORM_ID       NUMBER(19)   NOT NULL,
    USER_ID       NUMBER(19),
    STATUS        VARCHAR2(16) DEFAULT 'SUBMITTED' NOT NULL,
    SUBMITTED_AT  TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    IP_ADDR       VARCHAR2(64),
    USER_AGENT    VARCHAR2(512),
    ANON_TOKEN    VARCHAR2(64),
    CONSTRAINT FK_RESP_FORM FOREIGN KEY (FORM_ID) REFERENCES FORMS(ID) ON DELETE CASCADE,
    CONSTRAINT FK_RESP_USER FOREIGN KEY (USER_ID) REFERENCES USERS(ID) ON DELETE SET NULL,
    CONSTRAINT CHK_RESP_ST  CHECK (STATUS IN ('DRAFT','SUBMITTED'))
);
CREATE INDEX IX_RESP_FORM_TIME ON RESPONSES(FORM_ID, SUBMITTED_AT);
CREATE INDEX IX_RESP_USER      ON RESPONSES(USER_ID);

-- ---------- ANSWERS (EAV) ----------
CREATE TABLE ANSWERS (
    ID           NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RESPONSE_ID  NUMBER(19)    NOT NULL,
    QUESTION_ID  NUMBER(19)    NOT NULL,
    VALUE_TEXT   CLOB,
    VALUE_NUMBER NUMBER(20,4),
    VALUE_DATE   TIMESTAMP,
    FILE_PATH    VARCHAR2(1024),
    FILE_NAME    VARCHAR2(512),
    CONSTRAINT FK_ANS_RESP FOREIGN KEY (RESPONSE_ID) REFERENCES RESPONSES(ID) ON DELETE CASCADE,
    CONSTRAINT FK_ANS_Q    FOREIGN KEY (QUESTION_ID) REFERENCES QUESTIONS(ID) ON DELETE CASCADE
);
CREATE INDEX IX_ANS_RESP ON ANSWERS(RESPONSE_ID);
CREATE INDEX IX_ANS_Q    ON ANSWERS(QUESTION_ID);

-- ---------- ANSWER_OPTIONS (多選/單選紀錄) ----------
CREATE TABLE ANSWER_OPTIONS (
    ID         NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ANSWER_ID  NUMBER(19) NOT NULL,
    OPTION_ID  NUMBER(19) NOT NULL,
    CONSTRAINT FK_AO_ANS FOREIGN KEY (ANSWER_ID) REFERENCES ANSWERS(ID) ON DELETE CASCADE,
    CONSTRAINT FK_AO_OPT FOREIGN KEY (OPTION_ID) REFERENCES QUESTION_OPTIONS(ID) ON DELETE CASCADE
);
CREATE INDEX IX_AO_ANS ON ANSWER_OPTIONS(ANSWER_ID);
CREATE INDEX IX_AO_OPT ON ANSWER_OPTIONS(OPTION_ID);

-- ---------- AUDIT_LOGS ----------
CREATE TABLE AUDIT_LOGS (
    ID         NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID    NUMBER(19),
    ACTION     VARCHAR2(64) NOT NULL,
    TARGET     VARCHAR2(256),
    DETAIL     VARCHAR2(2000),
    IP_ADDR    VARCHAR2(64),
    CREATED_AT TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL
);

-- ---------- LOGIN_ATTEMPTS ----------
CREATE TABLE LOGIN_ATTEMPTS (
    ID          NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME    VARCHAR2(128),
    IP_ADDR     VARCHAR2(64),
    SUCCESS     CHAR(1)      DEFAULT 'N' NOT NULL,
    ATTEMPTED_AT TIMESTAMP   DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CHK_LA_S CHECK (SUCCESS IN ('Y','N'))
);
CREATE INDEX IX_LA_TIME ON LOGIN_ATTEMPTS(USERNAME, ATTEMPTED_AT);

COMMIT;
